def shell_lines(*args: str) -> list[str]:
    return subprocess.check_output(args, text=True, stderr=subprocess.DEVNULL).splitlines()


def load_strings(path: Path) -> dict[str, str]:
    data = subprocess.check_output(["plutil", "-convert", "json", "-o", "-", str(path)])
    return json.loads(data)


def is_resource_key(s: str) -> bool:
    return bool(re.match(r"^[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*\.[A-Za-z].*$", s) or re.match(r"^\d+\.[A-Za-z].*$", s))


def clean_candidate(s: str) -> bool:
    if not s:
        return False
    if is_resource_key(s):
        return False
    if s.startswith(("NS", "IB", "_NS")):
        return False
    if re.match(r"^[{}0-9, .@%:-]+$", s):
        return False
    if s.endswith(":") and "self." in s:
        return False
    if s in {"system", "tortoise", "hare", "scissors", "creditcard"}:
        return False
    return True


def extract_nib_english(nib: Path, keys: list[str]) -> dict[str, str]:
    if not nib.exists():
        return {}
    lines = shell_lines("strings", "-a", str(nib))
    positions: dict[str, int] = {}
    for i, line in enumerate(lines):
        if line in keys and line not in positions:
            positions[line] = i

    out: dict[str, str] = {}
    for key in keys:
        i = positions.get(key)
        if i is None:
            continue
        for j in (i - 1, i + 1, i - 2, i + 2, i - 3, i + 3):
            if 0 <= j < len(lines) and clean_candidate(lines[j]):
                out[key] = lines[j]
                break
    return out


def extract_strings_comment_english(path: Path) -> dict[str, str]:
    data = path.read_bytes()
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        text = data.decode("utf-16")
    else:
        text = data.decode("utf-8-sig")

    out: dict[str, str] = {}
    pending_value: str | None = None
    property_pattern = re.compile(
        r'^\s*/\* Class = "[^"]+"; (?:title|label|placeholderString|ibShadowedToolTip|ibExternalAccessibilityDescription)\s*=\s*"((?:\\.|[^"])*)"'
    )
    key_pattern = re.compile(r'^"((?:\\.|[^"])*)"\s*=')

    for line in text.splitlines():
        property_match = property_pattern.search(line)
        if property_match:
            pending_value = json.loads(f'"{property_match.group(1)}"')
            continue

        key_match = key_pattern.match(line.strip())
        if key_match and pending_value is not None:
            key = json.loads(f'"{key_match.group(1)}"')
            out[key] = pending_value
            pending_value = None

    return out


