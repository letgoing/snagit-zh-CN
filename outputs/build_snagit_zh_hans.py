def main() -> None:
    required = [SOURCE_LOCALE, BASE_LOCALE, COMMON_SOURCE, HELPER_SOURCE_LOCALE, HELPER_BASE_LOCALE]
    missing = [str(path) for path in required if not path.exists()]
    if missing:
        raise SystemExit("Missing Snagit resources:\n" + "\n".join(missing))

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    translated_files = 0
    translated_entries = 0
    total_entries = 0

    for src in sorted(SOURCE_LOCALE.glob("*.strings")):
        source_items = load_strings(src)
        total_entries += len(source_items)
        out_items: dict[str, str] = {}

        if src.name in {"Localizable.strings", "InfoPlist.strings"}:
            for key in source_items:
                value = translate(key)
                if value:
                    out_items[key] = value
            if src.name == "Localizable.strings":
                out_items.update(EXTRA_LOCALIZABLE)
        else:
            out_items = interface_items(src, BASE_LOCALE, source_items)

        if out_items:
            write_strings(OUT / src.name, out_items)
            translated_files += 1
            translated_entries += len(out_items)

    print(f"Generated {OUT}")
    print(f"Translated entries: {translated_entries}/{total_entries} in {translated_files} files")

    bad = []
    for f in OUT.glob("*.strings"):
        proc = subprocess.run(["plutil", "-lint", str(f)], text=True, capture_output=True)
        if proc.returncode != 0:
            bad.append((f.name, proc.stdout, proc.stderr))
    if bad:
        print("Invalid strings files:")
        for name, stdout, stderr in bad:
            print(name, stdout, stderr)
        raise SystemExit(1)

    common_translated, common_total = generate_common_framework()
    common_file = COMMON_OUT / "SnagitCommon.strings"
    proc = subprocess.run(["plutil", "-lint", str(common_file)], text=True, capture_output=True)
    if proc.returncode != 0:
        print("Invalid SnagitCommon strings file:")
        print(proc.stdout, proc.stderr)
        raise SystemExit(1)
    print(f"Generated {COMMON_OUT}")
    print(f"Translated SnagitCommon entries: {common_translated}/{common_total}")

    helper_translated, helper_total, helper_files = generate_helper_app()
    helper_bad = []
    for helper_file in HELPER_OUT.glob("*.strings"):
        helper_proc = subprocess.run(["plutil", "-lint", str(helper_file)], text=True, capture_output=True)
        if helper_proc.returncode != 0:
            helper_bad.append((helper_file.name, helper_proc.stdout, helper_proc.stderr))
    if helper_bad:
        print("Invalid SnagitHelper strings files:")
        for name, stdout, stderr in helper_bad:
            print(name, stdout, stderr)
        raise SystemExit(1)
    print(f"Generated {HELPER_OUT}")
    print(f"Translated SnagitHelper entries: {helper_translated}/{helper_total} in {helper_files} files")


if __name__ == "__main__":
    main()
