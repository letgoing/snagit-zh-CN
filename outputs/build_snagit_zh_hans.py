def translate_template_name(text: str) -> str | None:
    for theme_en, theme_zh in THEME_NAMES.items():
        prefix = f"{theme_en} "
        if not text.startswith(prefix):
            continue
        rest = text[len(prefix):]
        for layout_en, layout_zh in sorted(LAYOUT_NAMES.items(), key=lambda item: len(item[0]), reverse=True):
            layout_prefix = f"{layout_en} "
            if not rest.startswith(layout_prefix):
                continue
            orientation = rest[len(layout_prefix):]
            if orientation in ORIENTATIONS:
                return f"{theme_zh} - {layout_zh}（{ORIENTATIONS[orientation]}）"
        if rest in LAYOUT_NAMES:
            return f"{theme_zh} - {LAYOUT_NAMES[rest]}"
    return None


def translate(text: str) -> str | None:
    if text in EXACT:
        return EXACT[text]

    if text in PHRASES:
        return PHRASES[text]

    template_name = translate_template_name(text)
    if template_name:
        return template_name

    if text.endswith("..."):
        base = text[:-3]
        got = translate(base)
        return f"{got}..." if got else None

    if text.endswith("…"):
        base = text[:-1]
        got = translate(base)
        return f"{got}…" if got else None

    if text.endswith(":"):
        got = translate(text[:-1])
        return f"{got}：" if got else None

    max_match = re.fullmatch(r"(.+) \(max\. (\d+)\)", text)
    if max_match:
        got = translate(max_match.group(1))
        if got:
            return f"{got}（最多 {max_match.group(2)}）"

    selected = re.fullmatch(r"(.+) Selected \((.+)\)", text)
    if selected:
        got = translate(selected.group(1))
        if got:
            return f"已选择 {got}（{selected.group(2)}）"

    count_selected = re.fullmatch(r"(\d+) object selected", text)
    if count_selected:
        return f"已选择 {count_selected.group(1)} 个对象"

    pct = re.fullmatch(r"(.+): (%d|%@|%i|%ld|%lld)%%", text)
    if pct:
        got = translate(pct.group(1))
        if got:
            return f"{got}：{pct.group(2)}%"

    return None


